package com.company.incidentplatform.evidence;

import com.company.incidentplatform.error.ConflictException;
import jakarta.annotation.PostConstruct;
import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.nio.file.StandardOpenOption;
import java.util.UUID;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Component;

/**
 * Local-filesystem {@link EvidenceStorage}: a private directory, no web root, no
 * static handler.
 *
 * <p>This is the development binding for the bucket described in 5.1/7.6. It
 * exists so the upload and download paths can be built and tested against a real
 * filesystem, and it reproduces the two properties of the production bucket that
 * the application logic actually depends on:
 *
 * <ul>
 *   <li><b>Not reachable without going through the application.</b> 7.6 requires
 *       that files live outside the web root and are served only by an
 *       authorization-checked endpoint. Spring Boot serves static content from
 *       {@code classpath:/static} and the servlet container from its own document
 *       root; nothing here is under either, and {@link #verifyNotServable} refuses
 *       to start if an operator has pointed the root somewhere that would be.</li>
 *   <li><b>Write-once.</b> {@link #store} refuses an existing path, so no code
 *       path can replace an object that a hash already attests to.</li>
 * </ul>
 *
 * <h2>Path handling</h2>
 *
 * <p>{@code storage_path} values are generated by {@link #generateKey}, not
 * supplied by a caller, and are then resolved and checked against the root before
 * any I/O. The check is done on the <em>canonical</em> path so that {@code ..}
 * segments and symlinks cannot escape; a path that escapes is a bug or an attack
 * and is refused loudly rather than sanitised into something plausible.
 */
@Component
public class FileSystemEvidenceStorage implements EvidenceStorage {

    private static final Logger log = LoggerFactory.getLogger(FileSystemEvidenceStorage.class);

    private final Path root;
    private final String rootDescription;

    public FileSystemEvidenceStorage(EvidenceProperties properties) {
        this.root = Path.of(properties.getStorageRoot()).toAbsolutePath().normalize();
        this.rootDescription = this.root.toString();
    }

    @PostConstruct
    void verifyNotServable() throws IOException {
        if (!Files.isDirectory(root)) {
            Files.createDirectories(root);
            log.info("Created private evidence directory {}", root);
        }
        if (!Files.isWritable(root)) {
            throw new IllegalStateException(
                    "Evidence storage root " + rootDescription + " is not writable. Evidence cannot be stored.");
        }
        // Not a paranoid symlink check on the root itself: an operator who has
        // pointed the root at a served directory has misconfigured the
        // deployment, and the useful thing to do is say so plainly at startup
        // rather than to start up and quietly serve evidence.
        if (rootDescription.replace('\\', '/').contains("/static/")) {
            throw new IllegalStateException("Evidence storage root " + rootDescription
                    + " is inside a static resource directory. 7.6 requires evidence to be stored outside the "
                    + "web root and served only through authorization-checked download endpoints.");
        }
        log.info("Evidence storage bound to private directory {}", root);
    }

    /**
     * A storage key in the shape object storage uses: {@code
     * <yyyy>/<mm>/<dd>/<uuid>}.
     *
     * <p>Date-prefixed so that a bucket listing, a lifecycle rule, and the 7.14
     * retention process can all work on prefixes rather than by opening every
     * object -- and, more importantly, so that the key reveals nothing about the
     * uploader, the incident, or the original file name. The user's file name is
     * kept in the database as a label; the key is not derived from it.
     */
    public static String generateKey(UUID incidentId, UUID evidenceId, java.time.OffsetDateTime uploadedAt) {
        return "%04d/%02d/%02d/%s/%s".formatted(
                uploadedAt.getYear(),
                uploadedAt.getMonthValue(),
                uploadedAt.getDayOfMonth(),
                incidentId,
                evidenceId);
    }

    @Override
    public long store(String storagePath, InputStream content, long byteLimit) throws IOException {
        Path target = resolveInsideRoot(storagePath);
        if (Files.exists(target)) {
            // Write-once. 7.6: evidence is immutable post-upload, and the database
            // trigger protects the metadata -- this protects the bytes.
            throw new ConflictException(
                    "Evidence object already exists at this path; evidence is write-once (7.6).");
        }
        Path parent = target.getParent();
        if (parent != null) {
            Files.createDirectories(parent);
        }

        // Written to a sibling temp file and moved into place. A reader never
        // observes a partial object, so a concurrent download cannot fail its
        // hash check for a mundane reason.
        Path temporary = Files.createTempFile(parent, ".upload-", ".part");
        try {
            long written;
            try (OutputStream out = Files.newOutputStream(temporary, StandardOpenOption.WRITE)) {
                written = copyBounded(content, out, byteLimit);
            }
            try {
                Files.move(temporary, target, StandardCopyOption.ATOMIC_MOVE);
            } catch (java.nio.file.AtomicMoveNotSupportedException noAtomicMove) {
                // Some network filesystems cannot move atomically. A plain move is
                // still a rename within one directory, which is atomic in practice
                // on those, and the window it leaves is bounded by the fallback.
                log.warn("Atomic move unavailable for evidence storage at {}; using a plain move", parent);
                Files.move(temporary, target);
            }
            return written;
        } finally {
            Files.deleteIfExists(temporary);
        }
    }

    @Override
    public InputStream open(String storagePath) throws IOException {
        Path target = resolveInsideRoot(storagePath);
        if (!Files.isRegularFile(target)) {
            throw new java.nio.file.NoSuchFileException(storagePath);
        }
        return Files.newInputStream(target, StandardOpenOption.READ);
    }

    @Override
    public boolean exists(String storagePath) {
        try {
            return Files.isRegularFile(resolveInsideRoot(storagePath));
        } catch (IllegalArgumentException refused) {
            return false;
        }
    }

    @Override
    public void deleteForRetention(String storagePath, String reason) throws IOException {
        if (reason == null || reason.isBlank()) {
            // 7.6 requires deletion to be an audited event, and the reason is what
            // makes the row reconstructable. Refusing here rather than accepting a
            // null keeps the audit write and the delete inseparable.
            throw new IllegalArgumentException("Retention deletion requires a stated reason (7.6)");
        }
        Path target = resolveInsideRoot(storagePath);
        if (Files.deleteIfExists(target)) {
            log.info("Evidence object deleted by retention process: {} ({})", storagePath, reason);
        }
    }

    /**
     * Resolves a key inside the root, refusing anything that leaves it.
     *
     * <p>Canonicalisation first, so {@code ..} and symlinks are both covered, and
     * the containment test is on the canonical form rather than on the string --
     * a prefix test on a normalised string is defeated by {@code /var/evidenceX}
     * matching a {@code /var/evidence} prefix.
     */
    private Path resolveInsideRoot(String storagePath) {
        if (storagePath == null || storagePath.isBlank()) {
            throw new IllegalArgumentException("Storage path is required");
        }
        Path resolved = root.resolve(storagePath).normalize();
        if (!resolved.startsWith(root)) {
            throw new IllegalArgumentException("Storage path escapes the evidence root");
        }
        Path anchor = canonicalRoot();
        if (anchor == null) {
            throw new IllegalStateException("Evidence storage root " + rootDescription + " is not resolvable");
        }
        // The target of a write does not exist yet, so containment is proved
        // against the deepest ancestor that does. A symlinked ancestor pointing
        // out of the root is caught here; a plain ".." was already removed by
        // normalize() and the startsWith test above.
        Path existing = resolved;
        while (existing != null && !Files.exists(existing)) {
            existing = existing.getParent();
        }
        if (existing == null) {
            throw new IllegalArgumentException("Storage path escapes the evidence root");
        }
        try {
            if (!existing.toRealPath().startsWith(anchor)) {
                throw new IllegalArgumentException("Storage path escapes the evidence root");
            }
        } catch (IOException unreadable) {
            throw new IllegalStateException("Evidence storage root " + rootDescription + " is not readable", unreadable);
        }
        return resolved;
    }

    private Path canonicalRoot() {
        try {
            return root.toRealPath();
        } catch (IOException notYetCreated) {
            return null;
        }
    }

    /**
     * Copies at most {@code byteLimit} bytes and fails if there were more.
     *
     * <p>Refusing beats truncating for evidence: a truncated file whose hash is
     * recorded as authoritative is a chain-of-custody record of content that was
     * never uploaded, and nothing downstream can tell the difference.
     */
    private static long copyBounded(InputStream in, OutputStream out, long byteLimit) throws IOException {
        byte[] buffer = new byte[64 * 1024];
        long total = 0;
        int read;
        while ((read = in.read(buffer)) != -1) {
            total += read;
            if (total > byteLimit) {
                throw new IllegalArgumentException(
                        "Evidence content exceeded the configured limit of " + byteLimit + " bytes");
            }
            out.write(buffer, 0, read);
        }
        return total;
    }
}
